#!/usr/bin/env python3
"""Write glide/site/tokens.css from glide/frontend/tokens.ts, so the landing page wears the same tokens as
the cards. The groups tokens.ts reads from the shared theme file (Dash's night, the gold, radii, type ramp and
tracking) are read here from the same pinned copy, glide/themes/shared/glide.json. The page's own stylesheet uses only these variables; tests/test_site.py fails on drift.

    python glide/tools/site_tokens.py          # rewrite glide/site/tokens.css
    python glide/tools/site_tokens.py --check  # exit 1 if it is stale
"""
from __future__ import annotations

import json
import re
import sys
from pathlib import Path

GLIDE = Path(__file__).resolve().parents[1]
TOKENS = GLIDE / "frontend" / "tokens.ts"
SHARED = GLIDE / "themes" / "shared" / "glide.json"
OUT = GLIDE / "site" / "tokens.css"
GROUPS = {"DASH": "dash", "NIGHT": "night", "GOLD": "gold", "STATUS": "status", "RADIUS": "r", "TYPE": "t", "TRACK": "track"}
PX = ("RADIUS", "TYPE")


def kebab(name: str) -> str:
    return re.sub(r"(?<=[a-z0-9])([A-Z])", r"-\1", name).lower()


def shared_groups(theme: dict) -> dict[str, dict[str, str]]:
    """tokens.ts's groups that come from the shared theme, named as tokens.ts names them."""
    night, brand = theme["color"]["dark"], theme["brand"]
    return {
        "DASH": {"bg": night["bg"], "fg": night["fg"], "gold": brand["accent"], "muted": night["mutedFg"],
                 "dim": night["faint"], "error": night["danger"], "success": night["success"]},
        "GOLD": dict(brand["cta"]),
        "RADIUS": {k: str(theme["radius"][k]) for k in ("chip", "tile", "block", "card", "pill")},
        "TYPE": {k: str(v) for k, v in theme["type"]["size"].items()},
        "TRACK": dict(theme["type"]["tracking"]),
    }


def parse(source: str, theme: dict | None = None) -> dict[str, dict[str, str]]:
    groups = shared_groups(json.loads(SHARED.read_text()) if theme is None else theme)
    for name, body in re.findall(r"export const (\w+) = \{(.*?)\} as const", source, re.S):
        if name in groups:
            continue
        values: dict[str, str] = {}
        for key, value in re.findall(r"(\w+):\s*('[^']*'|[\d.]+|[A-Z]+\.\w+)", re.sub(r"//[^\n]*", "", body)):
            if value.startswith("'"):
                values[key] = value[1:-1]
            elif "." in value and value[0].isalpha():
                group, ref = value.split(".")
                values[key] = groups[group][ref]
            else:
                values[key] = value
        groups[name] = values
    for name, value in re.findall(r"export const (\w+) = ('[^']*'|\"[^\"]*\")\s*$", source, re.M):
        groups[name] = {"": value[1:-1]}
    return groups


def render(source: str, theme: dict | None = None) -> str:
    groups = parse(source, theme)
    lines = ["/* Generated by glide/tools/site_tokens.py from glide/frontend/tokens.ts and glide/themes/shared/glide.json. Do not edit. */", ":root {"]
    for name, prefix in GROUPS.items():
        for key, value in groups[name].items():
            lines.append(f"  --{prefix}-{kebab(key)}: {value}{'px' if name in PX else ''};")
    lines.append(f"  --council: {groups['COUNCIL_HUE']['']};")
    for name in ("SERIF", "MONO"):
        lines.append(f"  --font-{name.lower()}: {groups[name]['']};")
    lines.append("}")
    return "\n".join(lines) + "\n"


def main() -> int:
    want = render(TOKENS.read_text())
    if "--check" in sys.argv[1:]:
        if not OUT.exists() or OUT.read_text() != want:
            print(f"{OUT.relative_to(GLIDE.parent)} is stale: run python glide/tools/site_tokens.py")
            return 1
        print("site tokens: fresh")
        return 0
    OUT.write_text(want)
    print(f"wrote {OUT.relative_to(GLIDE.parent)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
